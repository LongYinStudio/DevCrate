export type IndentStyle = 'space' | 'tab';
export type EndOfLineMode = 'lf' | 'crlf' | 'cr' | 'auto';
export type CharsetMode = 'utf-8' | 'utf-8-bom' | 'latin1';
export type TrailingCommaMode = 'all' | 'es5' | 'none';
export type ArrowParensMode = 'always' | 'avoid';
export type ProseWrapMode = 'preserve' | 'always' | 'never';
export type HtmlWhitespaceMode = 'css' | 'strict' | 'ignore';
export type EmbeddedFormattingMode = 'auto' | 'off';
export type PrettierOutputFormat = 'json' | 'yaml' | 'mjs';

export interface EditorConfigOverride {
  id: string;
  enabled: boolean;
  glob: string;
  indentStyle?: IndentStyle;
  indentSize?: number;
  trimTrailingWhitespace?: boolean;
  insertFinalNewline?: boolean;
  maxLineLength?: string; // e.g. "off" or "120"
  charset?: CharsetMode;
}

export interface PrettierOverrideRule {
  id: string;
  enabled: boolean;
  files: string; // comma-separated globs, e.g. "*.md, *.mdx"
  tabWidth?: number;
  useTabs?: boolean;
  singleQuote?: boolean;
  semi?: boolean;
  printWidth?: number;
  proseWrap?: ProseWrapMode;
  trailingComma?: TrailingCommaMode;
}

export interface StyleSyncConfig {
  // Shared synced properties
  indentStyle: IndentStyle;
  indentSize: number;
  endOfLine: EndOfLineMode;
  printWidth: number;
  syncMaxLineLengthToEditorConfig: boolean;

  // .editorconfig global options
  root: boolean;
  charset: CharsetMode;
  trimTrailingWhitespace: boolean;
  insertFinalNewline: boolean;
  includeEditorConfigComments: boolean;
  editorConfigOverrides: EditorConfigOverride[];

  // Prettier global options
  prettierFormat: PrettierOutputFormat;
  semi: boolean;
  singleQuote: boolean;
  jsxSingleQuote: boolean;
  trailingComma: TrailingCommaMode;
  bracketSpacing: boolean;
  bracketSameLine: boolean;
  arrowParens: ArrowParensMode;
  proseWrap: ProseWrapMode;
  singleAttributePerLine: boolean;
  vueIndentScriptAndStyle: boolean;
  htmlWhitespaceSensitivity: HtmlWhitespaceMode;
  embeddedLanguageFormatting: EmbeddedFormattingMode;
  plugins: string[];
  prettierOverrides: PrettierOverrideRule[];

  // .prettierignore patterns
  prettierIgnoreLines: string[];
}

export interface StyleAuditIssue {
  level: 'error' | 'warning' | 'info';
  code: string;
  messageZh: string;
  messageEn: string;
  fixable?: 'fix-md-whitespace' | 'fix-makefile-tab' | 'fix-eol-lf';
}

let seq = 1;
export function createStyleRuleId(prefix = 'ov'): string {
  return `${prefix}-${Date.now()}-${seq++}`;
}

