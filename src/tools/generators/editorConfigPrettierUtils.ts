export function generateEditorConfig(config: StyleSyncConfig): string {
  const lines: string[] = [];

  if (config.includeEditorConfigComments) {
    lines.push('# EditorConfig is awesome: https://EditorConfig.org');
    lines.push('# Generated by DevCrate - .editorconfig & Prettier Co-Generator');
    lines.push('');
  }

  if (config.root) {
    lines.push('root = true');
    lines.push('');
  }

  lines.push('[*]');
  lines.push(`charset = ${config.charset}`);
  if (config.endOfLine !== 'auto') {
    lines.push(`end_of_line = ${config.endOfLine}`);
  }
  lines.push(`indent_style = ${config.indentStyle}`);
  lines.push(`indent_size = ${config.indentSize}`);
  if (config.indentStyle === 'tab') {
    lines.push(`tab_width = ${config.indentSize}`);
  }
  lines.push(`trim_trailing_whitespace = ${config.trimTrailingWhitespace}`);
  lines.push(`insert_final_newline = ${config.insertFinalNewline}`);
  if (config.syncMaxLineLengthToEditorConfig && config.printWidth > 0) {
    lines.push(`max_line_length = ${config.printWidth}`);
  }

  for (const ov of config.editorConfigOverrides) {
    const glob = ov.glob.trim();
    if (!ov.enabled || !glob) continue;
    lines.push('');
    lines.push(`[${glob}]`);
    if (ov.charset) lines.push(`charset = ${ov.charset}`);
    if (ov.indentStyle) lines.push(`indent_style = ${ov.indentStyle}`);
    if (ov.indentSize !== undefined && ov.indentSize > 0) {
      lines.push(`indent_size = ${ov.indentSize}`);
    }
    if (ov.trimTrailingWhitespace !== undefined) {
      lines.push(`trim_trailing_whitespace = ${ov.trimTrailingWhitespace}`);
    }
    if (ov.insertFinalNewline !== undefined) {
      lines.push(`insert_final_newline = ${ov.insertFinalNewline}`);
    }
    if (ov.maxLineLength && ov.maxLineLength.trim()) {
      lines.push(`max_line_length = ${ov.maxLineLength.trim()}`);
    }
  }

  return `${lines.join('\n')}\n`;
}

export function buildPrettierObject(config: StyleSyncConfig): Record<string, unknown> {
  const obj: Record<string, unknown> = {
    printWidth: config.printWidth,
    tabWidth: config.indentSize,
    useTabs: config.indentStyle === 'tab',
    semi: config.semi,
    singleQuote: config.singleQuote,
    jsxSingleQuote: config.jsxSingleQuote,
    trailingComma: config.trailingComma,
    bracketSpacing: config.bracketSpacing,
    bracketSameLine: config.bracketSameLine,
    arrowParens: config.arrowParens,
    endOfLine: config.endOfLine,
    proseWrap: config.proseWrap,
    htmlWhitespaceSensitivity: config.htmlWhitespaceSensitivity,
    vueIndentScriptAndStyle: config.vueIndentScriptAndStyle,
    singleAttributePerLine: config.singleAttributePerLine,
    embeddedLanguageFormatting: config.embeddedLanguageFormatting,
  };

  if (config.plugins.length > 0) {
    obj.plugins = [...config.plugins];
  }

  const activeOverrides = config.prettierOverrides
    .filter((o) => o.enabled && o.files.trim())
    .map((o) => {
      const filesList = o.files
        .split(',')
        .map((f) => f.trim())
        .filter(Boolean);
      const options: Record<string, unknown> = {};
      if (o.tabWidth !== undefined && o.tabWidth > 0) options.tabWidth = o.tabWidth;
      if (o.useTabs !== undefined) options.useTabs = o.useTabs;
      if (o.singleQuote !== undefined) options.singleQuote = o.singleQuote;
      if (o.semi !== undefined) options.semi = o.semi;
      if (o.printWidth !== undefined && o.printWidth > 0) options.printWidth = o.printWidth;
      if (o.proseWrap !== undefined) options.proseWrap = o.proseWrap;
      if (o.trailingComma !== undefined) options.trailingComma = o.trailingComma;
      return {
        files: filesList.length === 1 ? filesList[0] : filesList,
        options,
      };
    })
    .filter((o) => Object.keys(o.options).length > 0);

  if (activeOverrides.length > 0) {
    obj.overrides = activeOverrides;
  }

  return obj;
}

function toYamlScalar(val: unknown): string {
  if (typeof val === 'boolean' || typeof val === 'number') return String(val);
  const str = String(val);
  if (/^[a-zA-Z0-9_.-]+$/.test(str)) return str;
  return JSON.stringify(str);
}

function serializeSimpleYaml(obj: unknown, indent = 0): string {
  const pad = '  '.repeat(indent);
  if (Array.isArray(obj)) {
    return obj
      .map((item) => {
        if (item !== null && typeof item === 'object') {
          const inner = serializeSimpleYaml(item, indent + 1);
          const firstLineIdx = inner.indexOf('\n');
          if (firstLineIdx < 0) {
            return `${pad}- ${inner.trimStart()}`;
          }
          return `${pad}- ${inner.slice(0, firstLineIdx).trimStart()}\n${inner.slice(firstLineIdx + 1)}`;
        }
        return `${pad}- ${toYamlScalar(item)}`;
      })
      .join('\n');
  }
  if (obj !== null && typeof obj === 'object') {
    return Object.entries(obj as Record<string, unknown>)
      .map(([k, v]) => {
        if (Array.isArray(v) || (v !== null && typeof v === 'object')) {
          return `${pad}${k}:\n${serializeSimpleYaml(v, indent + 1)}`;
        }
        return `${pad}${k}: ${toYamlScalar(v)}`;
      })
      .join('\n');
  }
  return `${pad}${toYamlScalar(obj)}`;
}

export function getPrettierFilename(format: PrettierOutputFormat): string {
  if (format === 'yaml') return '.prettierrc.yaml';
  if (format === 'mjs') return 'prettier.config.mjs';
  return '.prettierrc.json';
}

export function generatePrettierConfig(config: StyleSyncConfig): string {
  const obj = buildPrettierObject(config);
  if (config.prettierFormat === 'yaml') {
    return `# Prettier configuration\n${serializeSimpleYaml(obj)}\n`;
  }
  if (config.prettierFormat === 'mjs') {
    const jsonBody = JSON.stringify(obj, null, 2);
    return `/** @type {import("prettier").Config} */\nconst config = ${jsonBody};\n\nexport default config;\n`;
  }
  return `${JSON.stringify(obj, null, 2)}\n`;
}

export function generatePrettierIgnore(config: StyleSyncConfig): string {
  const cleaned = config.prettierIgnoreLines.map((l) => l.trim()).filter(Boolean);
  return `# Ignore build artifacts & lockfiles\n${cleaned.join('\n')}\n`;
}

export function renderLivePreviewSample(config: StyleSyncConfig): string {
  const ind = config.indentStyle === 'tab' ? '\t' : ' '.repeat(config.indentSize);
  const q = config.singleQuote ? "'" : '"';
  const s = config.semi ? ';' : '';
  const bs = config.bracketSpacing ? ' ' : '';
  const tcAll = config.trailingComma === 'all' ? ',' : '';
  const tcEs5 = config.trailingComma === 'none' ? '' : ',';
  const paramWrapped = config.arrowParens === 'always' ? '(item)' : 'item';

  const lines = [
    `import {${bs}formatUser, type UserProfile${bs}} from ${q}./utils/user${q}${s}`,
    '',
    `export const DEFAULT_CONFIG = {`,
    `${ind}theme: ${q}dark${q},`,
    `${ind}retries: 3${tcEs5}`,
    `}${s}`,
    '',
    `export function pickActiveNames(`,
    `${ind}users: UserProfile[],`,
    `${ind}includeGuest = false${tcAll}`,
    `): string[] {`,
    `${ind}return users`,
    `${ind}${ind}.filter(${paramWrapped} => item.active || includeGuest)`,
    `${ind}${ind}.map(${paramWrapped} => ${q}@${q} + item.name)${s}`,
    `}`,
  ];
  return lines.join('\n');
}

export function auditStyleConfig(config: StyleSyncConfig): StyleAuditIssue[] {
  const issues: StyleAuditIssue[] = [];

  if (config.endOfLine === 'cr') {
    issues.push({
      level: 'error',
      code: 'prettier-unsupported-cr',
      fixable: 'fix-eol-lf',
      messageZh: 'Prettier 不支持 endOfLine="cr"，仅支持 lf / crlf / auto；建议统一使用 lf。',
      messageEn: 'Prettier does not support endOfLine="cr" (only lf, crlf, auto). Switch to lf.',
    });
  }

  if (config.printWidth < 40 || config.printWidth > 240) {
    issues.push({
      level: 'warning',
      code: 'unusual-print-width',
      messageZh: `printWidth=${config.printWidth} 超出常见团队区间 (80 ~ 120)，可能导致代码过早折行或横向滚动。`,
      messageEn: `printWidth=${config.printWidth} is outside common team ranges (80-120).`,
    });
  }

  const activeEco = config.editorConfigOverrides.filter((o) => o.enabled);

  // Check Markdown trailing whitespace rule
  if (config.trimTrailingWhitespace) {
    const mdRule = activeEco.find((o) => /\*\.md\b/i.test(o.glob));
    if (!mdRule || mdRule.trimTrailingWhitespace !== false) {
      issues.push({
        level: 'warning',
        code: 'md-trailing-whitespace',
        fixable: 'fix-md-whitespace',
        messageZh: '全局开启了 trim_trailing_whitespace = true，但未给 [*.md] 设置 false，保存 Markdown 时会误删双空格硬换行。',
        messageEn: 'Global trim_trailing_whitespace=true without a [*.md] exception strips Markdown 2-space hard line breaks.',
      });
    }
  }

  // Check Makefile tab requirement when global indent is spaces
  if (config.indentStyle === 'space') {
    const makeRule = activeEco.find((o) => /makefile/i.test(o.glob));
    if (!makeRule || makeRule.indentStyle !== 'tab') {
      issues.push({
        level: 'warning',
        code: 'makefile-needs-tab',
        fixable: 'fix-makefile-tab',
        messageZh: '全局使用空格缩进，建议在 .editorconfig 中为 [Makefile] 添加 indent_style = tab（Make 语法强制要求真实 Tab）。',
        messageEn: 'Global indent uses spaces; add a [Makefile] indent_style = tab override so Make targets remain valid.',
      });
    }
  }

  if (config.syncMaxLineLengthToEditorConfig && config.printWidth > 0) {
    issues.push({
      level: 'info',
      code: 'max-line-length-info',
      messageZh: `已将 max_line_length = ${config.printWidth} 同步写入 .editorconfig，部分 IDE 会在第 ${config.printWidth} 列绘制标尺提示线。`,
      messageEn: `Synced max_line_length = ${config.printWidth} to .editorconfig (renders ruler guides in supporting IDEs).`,
    });
  }

  return issues;
}

export function parseImportedStyleFile(raw: string): {
  kind: 'prettier' | 'editorconfig';
  patch: Partial<StyleSyncConfig>;
} {
  const trimmed = raw.trim();
  if (!trimmed) {
    throw new Error('Empty configuration content');
  }

  if (trimmed.startsWith('{')) {
    const parsed = JSON.parse(trimmed) as Record<string, unknown>;
    const patch: Partial<StyleSyncConfig> = {};
    if (typeof parsed.printWidth === 'number') patch.printWidth = parsed.printWidth;
    if (typeof parsed.tabWidth === 'number') patch.indentSize = parsed.tabWidth;
    if (typeof parsed.useTabs === 'boolean') patch.indentStyle = parsed.useTabs ? 'tab' : 'space';
    if (typeof parsed.semi === 'boolean') patch.semi = parsed.semi;
    if (typeof parsed.singleQuote === 'boolean') patch.singleQuote = parsed.singleQuote;
    if (typeof parsed.jsxSingleQuote === 'boolean') patch.jsxSingleQuote = parsed.jsxSingleQuote;
    if (parsed.trailingComma === 'all' || parsed.trailingComma === 'es5' || parsed.trailingComma === 'none') {
      patch.trailingComma = parsed.trailingComma;
    }
    if (typeof parsed.bracketSpacing === 'boolean') patch.bracketSpacing = parsed.bracketSpacing;
    if (typeof parsed.bracketSameLine === 'boolean') patch.bracketSameLine = parsed.bracketSameLine;
    if (parsed.arrowParens === 'always' || parsed.arrowParens === 'avoid') {
      patch.arrowParens = parsed.arrowParens;
    }
    if (parsed.endOfLine === 'lf' || parsed.endOfLine === 'crlf' || parsed.endOfLine === 'auto') {
      patch.endOfLine = parsed.endOfLine;
    }
    if (parsed.proseWrap === 'preserve' || parsed.proseWrap === 'always' || parsed.proseWrap === 'never') {
      patch.proseWrap = parsed.proseWrap;
    }
    if (typeof parsed.vueIndentScriptAndStyle === 'boolean') {
      patch.vueIndentScriptAndStyle = parsed.vueIndentScriptAndStyle;
    }
    if (typeof parsed.singleAttributePerLine === 'boolean') {
      patch.singleAttributePerLine = parsed.singleAttributePerLine;
    }
    if (
      parsed.htmlWhitespaceSensitivity === 'css' ||
      parsed.htmlWhitespaceSensitivity === 'strict' ||
      parsed.htmlWhitespaceSensitivity === 'ignore'
    ) {
      patch.htmlWhitespaceSensitivity = parsed.htmlWhitespaceSensitivity;
    }
    if (Array.isArray(parsed.plugins)) {
      patch.plugins = parsed.plugins.filter((p): p is string => typeof p === 'string');
    }
    return { kind: 'prettier', patch };
  }

  // Parse .editorconfig INI sections
  const patch: Partial<StyleSyncConfig> = {};
  const importedOverrides: EditorConfigOverride[] = [];
  let section = '';
  let currentOv: EditorConfigOverride | null = null;

  for (const rawLine of trimmed.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#') || line.startsWith(';')) continue;
    const secMatch = /^\[(.+)\]$/.exec(line);
    if (secMatch) {
      if (currentOv) importedOverrides.push(currentOv);
      section = secMatch[1].trim();
      currentOv =
        section === '*'
          ? null
          : {
              id: createStyleRuleId('ec'),
              enabled: true,
              glob: section,
            };
      continue;
    }

    const eqIdx = line.indexOf('=');
    if (eqIdx <= 0) continue;
    const key = line.slice(0, eqIdx).trim().toLowerCase();
    const val = line.slice(eqIdx + 1).trim();

    if (!section && key === 'root') {
      patch.root = /^(true|1)$/i.test(val);
      continue;
    }

    if (section === '*') {
      if (key === 'charset' && (val === 'utf-8' || val === 'utf-8-bom' || val === 'latin1')) {
        patch.charset = val;
      } else if (key === 'end_of_line' && (val === 'lf' || val === 'crlf' || val === 'cr')) {
        patch.endOfLine = val;
      } else if (key === 'indent_style' && (val === 'space' || val === 'tab')) {
        patch.indentStyle = val;
      } else if (key === 'indent_size' && /^\d+$/.test(val)) {
        patch.indentSize = Number(val);
      } else if (key === 'trim_trailing_whitespace') {
        patch.trimTrailingWhitespace = /^(true|1)$/i.test(val);
      } else if (key === 'insert_final_newline') {
        patch.insertFinalNewline = /^(true|1)$/i.test(val);
      } else if (key === 'max_line_length' && /^\d+$/.test(val)) {
        patch.printWidth = Number(val);
        patch.syncMaxLineLengthToEditorConfig = true;
      }
    } else if (currentOv) {
      if (key === 'indent_style' && (val === 'space' || val === 'tab')) {
        currentOv.indentStyle = val;
      } else if (key === 'indent_size' && /^\d+$/.test(val)) {
        currentOv.indentSize = Number(val);
      } else if (key === 'trim_trailing_whitespace') {
        currentOv.trimTrailingWhitespace = /^(true|1)$/i.test(val);
      } else if (key === 'insert_final_newline') {
        currentOv.insertFinalNewline = /^(true|1)$/i.test(val);
      } else if (key === 'max_line_length') {
        currentOv.maxLineLength = val;
      }
    }
  }
  if (currentOv) importedOverrides.push(currentOv);
  if (importedOverrides.length > 0) {
    patch.editorConfigOverrides = importedOverrides;
  }

  return { kind: 'editorconfig', patch };
}
